from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 1600, 'height': 1000})
    errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: m.type == 'error' and 'ERR_TUNNEL' not in m.text and errs.append(m.text))
    pg.goto('http://localhost:4322/flecs/sandbox/'); pg.wait_for_timeout(2000)
    pg.screenshot(path='sbx/0.png')
    insp = pg.locator('.sbx-insp')
    pg.locator('.sbx-ent', has_text='Rock').click(); pg.wait_for_timeout(200)
    insp.locator('select').first.select_option('Velocity'); insp.get_by_role('button', name='Add').click(); pg.wait_for_timeout(150)
    pg.screenshot(path='sbx/1.png')
    insp.locator('select').first.select_option('Frozen'); insp.get_by_role('button', name='Add').click(); pg.wait_for_timeout(700)
    pg.get_by_role('button', name='Run a frame').click(); pg.wait_for_timeout(300)
    pg.screenshot(path='sbx/2.png')
    pg.get_by_role('button', name='+ New entity').click(); pg.wait_for_timeout(200)
    insp.get_by_role('button', name='Delete').click(); pg.wait_for_timeout(200)
    pg.locator('.sbx-bar select').select_option('traits'); pg.wait_for_timeout(500)
    pg.locator('.sbx-ent', has_text='A').first.click()
    for c in ['Burning', 'Shield', 'Selected', 'Health']:
        insp.locator('select').first.select_option(c); insp.get_by_role('button', name='Add').click(); pg.wait_for_timeout(150)
    pg.get_by_role('button', name='Run a frame').click(); pg.wait_for_timeout(700)
    pg.screenshot(path='sbx/3.png')
    pg.locator('.sbx-bar select').select_option('fragmentation'); pg.wait_for_timeout(500)
    pg.get_by_role('button', name='Run a frame').click(); pg.wait_for_timeout(700)
    pg.screenshot(path='sbx/4.png')
    print('log0:', pg.locator('.sbx-entry').first.inner_text()[:400])
    print('errors', errs)
    pg.set_viewport_size({'width': 390, 'height': 900}); pg.wait_for_timeout(300)
    print('hscroll', pg.evaluate('document.documentElement.scrollWidth'))
    pg.screenshot(path='sbx/phone.png')
    b.close()
